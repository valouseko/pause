(() => {
  const storageKey = 'pause-language';
  const supported = language => language === 'cs' || language === 'en';
  const elements = [...document.querySelectorAll('[data-i18n]')];
  const czech = Object.fromEntries(elements.map(element => [element.dataset.i18n, element.innerHTML]));
  const buttons = [...document.querySelectorAll('[data-language]')];
  const descriptions = {
    cs: document.querySelector('meta[name="description"]').content,
    en: 'Pause gives you a moment to breathe before opening a distracting app. Free for Android. Step-by-step installation help for your phone.'
  };

  function readPreference() {
    try { return localStorage.getItem(storageKey); } catch { return null; }
  }

  function setLanguage(language, remember = false) {
    const translations = language === 'en' ? english : czech;
    elements.forEach(element => {
      element.innerHTML = translations[element.dataset.i18n];
    });
    document.documentElement.lang = language;
    document.title = language === 'en' ? 'Pause - a moment to think' : 'Pause - vteřina na rozmyšlenou';
    document.querySelector('meta[name="description"]').content = descriptions[language];
    buttons.forEach(button => {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });
    if (remember) {
      try { localStorage.setItem(storageKey, language); } catch { /* Storage can be disabled. */ }
    }
  }

  function languageFromLocation() {
    const requested = new URLSearchParams(location.search).get('lang');
    const saved = readPreference();
    const browserLanguages = navigator.languages || [navigator.language];
    const browserLanguage = browserLanguages.find(language => /^(cs|en)(-|$)/i.test(language));
    const fallback = browserLanguage && /^cs(-|$)/i.test(browserLanguage) ? 'cs' : 'en';
    setLanguage(supported(requested) ? requested : supported(saved) ? saved : fallback);
  }

  buttons.forEach(button => {
    button.addEventListener('click', () => {
      const language = button.dataset.language;
      setLanguage(language, true);
      const url = new URL(location.href);
      url.searchParams.set('lang', language);
      history.replaceState(null, '', url);
    });
  });

  // Open linked troubleshooting entries before scrolling to them.
  function revealAnchor() {
    const target = document.getElementById(location.hash.slice(1));
    if (target && target.tagName === 'DETAILS') {
      target.open = true;
      target.scrollIntoView({ block: 'start' });
    }
  }
  document.addEventListener('click', event => {
    const link = event.target.closest('a[href^="#"]');
    if (!link) return;
    const target = document.getElementById(link.hash.slice(1));
    if (target && target.tagName === 'DETAILS') target.open = true;
  });
  window.addEventListener('hashchange', revealAnchor);
  window.addEventListener('popstate', languageFromLocation);
  languageFromLocation();
  revealAnchor();
})();
